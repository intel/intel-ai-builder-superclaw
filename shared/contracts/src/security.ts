/**
 * Security-tab knobs shared between the LLMRouter Manager, the container-side
 * file-protection tool, and the UI.
 *
 * Two GET/PUT pairs under ``/llm-router/v1/data-protection/*``:
 *
 *   /mode              — FILE_PROTECTION_MODE (none | deterministic | hybrid | llm)
 *   /hybrid-threshold  — FILE_PROTECTION_HYBRID_THRESHOLD (float in [0, 1])
 *
 * Response shape follows the ``perf_weight`` convention: the persisted Store
 * value (nullable — null means "no override, using default"), the effective
 * ``applied`` value (which may come from an env override), and a ``source``
 * label so the UI can show "using env override" vs "using saved override".
 *
 * Authored once here in Zod; JSON Schema + Python Pydantic are generated by
 * ``scripts/gen.mjs``.
 */

import { z } from "zod";

/** The four selectable file-protection modes. */
export const FileProtectionModeSchema = z.enum([
  "none",
  "deterministic",
  "hybrid",
  "llm",
]);
export type FileProtectionMode = z.infer<typeof FileProtectionModeSchema>;

/** Which precedence layer produced the ``applied`` value. */
export const SourceSchema = z.enum(["env", "store", "default"]);
export type Source = z.infer<typeof SourceSchema>;

/** GET/PUT /mode response. */
export const FileProtectionModeStateSchema = z
  .object({
    /** Store override, or null when unset. */
    mode: FileProtectionModeSchema.nullable(),
    /** What the container-side tool will use right now. */
    applied: FileProtectionModeSchema,
    source: SourceSchema,
    supported: z.boolean(),
  })
  .strict();
export type FileProtectionModeState = z.infer<typeof FileProtectionModeStateSchema>;

/** PUT /mode body. ``mode: null`` clears the Store override. */
export const FileProtectionModeUpdateSchema = z
  .object({
    mode: FileProtectionModeSchema.nullable(),
  })
  .strict();
export type FileProtectionModeUpdate = z.infer<typeof FileProtectionModeUpdateSchema>;

/** GET/PUT /hybrid-threshold response. */
export const HybridThresholdStateSchema = z
  .object({
    /** Store override, or null when unset. */
    threshold: z.number().min(0).max(1).nullable(),
    /** What hybrid-mode dispatch will compare per-column confidence against. */
    applied: z.number().min(0).max(1),
    source: SourceSchema,
    supported: z.boolean(),
  })
  .strict();
export type HybridThresholdState = z.infer<typeof HybridThresholdStateSchema>;

/** PUT /hybrid-threshold body. ``threshold: null`` clears the Store override. */
export const HybridThresholdUpdateSchema = z
  .object({
    threshold: z.number().min(0).max(1).nullable(),
  })
  .strict();
export type HybridThresholdUpdate = z.infer<typeof HybridThresholdUpdateSchema>;
