/**
 * LocalCtxSize — llama-server ``-c`` context-size override.
 *
 * Wire shape for GET/PUT ``/llm-router/v1/local/ctx-size`` on the LLMRouter
 * Manager. Lets operators experiment with different context sizes without
 * rebuilding the installer or editing the shipping registry.
 *
 * Precedence (highest wins):
 *   1. env ``LATENTFACTOR_LOCAL_CTX``     (bench sweeps set this per shell)
 *   2. Store ``local_ctx_size_override``  (set by PUT; persists across restarts)
 *   3. booster ``tuned_args.ctx_size``    (hardware safety-net shrink)
 *   4. registry ``entry.default_ctx``     (baked into models.builtin.json)
 *
 * The PUT handler awaits ``supervisor.restart()`` before returning so the
 * new ``-c`` is actually running — ``-c`` is a llama-server launch flag,
 * not a runtime API.
 *
 * snake_case field names match the manager's endpoint convention (context_limit
 * / max_tokens / base_url, etc.). Authored once in Zod here; JSON Schema +
 * Python Pydantic are generated by ``scripts/gen.mjs``.
 */

import { z } from "zod";

/** Response of GET /local/ctx-size and PUT /local/ctx-size. */
export const LocalCtxSizeSchema = z
  .object({
    /** Persisted override in the Store, or null when unset. */
    ctx_size: z.number().int().min(1024).max(262144).nullable(),
    /** Value llama-server was launched with, or null if the supervisor hasn't published active tuning yet. */
    applied: z.number().int().positive().nullable(),
    /** Which layer the ``applied`` value came from: env / store / registry / booster / unknown. */
    source: z.enum(["env", "store", "registry", "booster", "unknown"]),
    /** True after a PUT that triggered a supervisor restart (the response is
     *  emitted after the restart completes). Absent on GET. */
    restarted: z.boolean().optional(),
    /** False when the local chat supervisor facade isn't available (e.g. unusual
     *  deployment / test fake without `restart()`); UI hides the panel. */
    supported: z.boolean(),
  })
  .strict();

export type LocalCtxSize = z.infer<typeof LocalCtxSizeSchema>;

/** Request body of PUT /local/ctx-size. ``ctx_size: null`` clears the override. */
export const LocalCtxSizeUpdateSchema = z
  .object({
    ctx_size: z.number().int().min(1024).max(262144).nullable(),
  })
  .strict();

export type LocalCtxSizeUpdate = z.infer<typeof LocalCtxSizeUpdateSchema>;
