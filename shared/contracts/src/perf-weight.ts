/**
 * PerfWeight — the quality-vs-cost balance dial for auto routing.
 *
 * Wire shape for GET/PUT ``/llm-router/v1/perf-weight`` on the LLMRouter
 * Manager. ``perf_weight`` is the coefficient in the LatentFactor balance score
 * ``balance = perf_weight * norm_perf - (1 - perf_weight) * norm_cost``: higher
 * biases routing toward the higher-performing model (typically cloud), lower
 * toward the cheaper model (typically local). ``supported`` is false when the
 * active router has no perf_weight knob — the UI hides the slider in that case.
 *
 * snake_case field names match the manager's endpoint convention (context_limit
 * / max_tokens / base_url, etc.). Authored once in Zod here; JSON Schema +
 * Python Pydantic are generated by ``scripts/gen.mjs``.
 */

import { z } from "zod";

/** Response of GET /perf-weight and PUT /perf-weight. */
export const PerfWeightSchema = z
  .object({
    perf_weight: z.number().min(0).max(1),
    supported: z.boolean(),
  })
  .strict();

export type PerfWeight = z.infer<typeof PerfWeightSchema>;

/** Request body of PUT /perf-weight. */
export const PerfWeightUpdateSchema = z
  .object({
    perf_weight: z.number().min(0).max(1),
  })
  .strict();

export type PerfWeightUpdate = z.infer<typeof PerfWeightUpdateSchema>;
