"""
Pydantic response models for protected file pipeline outputs.
"""

from typing import Optional

from pydantic import BaseModel, Field


# Protected file pipeline response models
class FinalResponse(BaseModel):
    source_file_path: str = Field(
        ...,
        description="Original source file path provided by the user, used by the protected file pipeline for dataset inspection and optional masking.",
    )

    masked_file_path: Optional[str] = Field(
        ...,
        description=(
            "Path to the masked output file generated from the user source file when sensitive entities are found and masking is performed by the `mask_sensitive_columns` tool. "
            "Use null if no sensitive entities are found or if masking is not required."
        ),
    )

    mask_registry_file_path: Optional[str] = Field(
        default=None,
        description=(
            "Path to the JSON mask registry generated by the `mask_sensitive_columns` tool during masking. "
            "Use null if no masking is required or if masking fails."
        ),
    )

    final_answer: str = Field(
        ...,
        description=(
            "Provide a concise final response to the user. Include the final status ('completed' or 'failed') and the key steps performed, and the generated masked file path when applicable. "
            "NEVER mention the mask registry file path or its location — it holds the raw, unmasked values and must never appear in this answer. "
            "If the workflow fails, clearly explain the error."
        ),
    )